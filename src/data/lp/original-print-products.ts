export const PRODUCTS: Product[] = ROWS.map(make);

export const PUBLISHED_PRODUCTS: Product[] = PRODUCTS.filter((p) => p.publish);
export const DEFAULT_PRODUCT_ID = "tshirt";

export function getProduct(id: string | null | undefined): Product | undefined {
  return PUBLISHED_PRODUCTS.find((p) => p.id === id);
}

/**
 * キーワード(URLパラメータ値)から商品を特定する。
 * 1) id の完全一致(`?item=class-tshirt` など)を最優先
 * 2) キーワードの部分一致は、最も長い(=具体的な)キーワードを持つ商品を採用する(「クラスTシャツ」>「Tシャツ」)
 * 3) 同じ長さで複数の商品に一致する場合は、曖昧なので特定しない
 */
export function detectProduct(values: string[]): Product | undefined {
  const cleaned = values.map((v) => v.trim().toLowerCase()).filter(Boolean);
  if (cleaned.length === 0) return undefined;

  for (const v of cleaned) {
    const byId = PUBLISHED_PRODUCTS.find((p) => p.id === v);
    if (byId) return byId;
  }

  const text = cleaned.join(" ");
  let best = 0;
  let winners: Product[] = [];
  for (const p of PUBLISHED_PRODUCTS) {
    for (const k of p.keywords) {
      if (!k || !text.includes(k)) continue;
      if (k.length > best) {
        best = k.length;
        winners = [p];
      } else if (k.length === best && !winners.includes(p)) {
        winners.push(p);
      }
    }
  }
  return winners.length === 1 ? winners[0] : undefined;
}
