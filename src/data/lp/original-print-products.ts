// Up-T LPの商品マスター(独立した設定ファイル)。
//
// 方針:
// - カテゴリーは、ユーザーから提示されたUp-Tの商品カテゴリ一覧画像(2026-10-15受領)に載っている項目に合わせて細分化した。
//   キャップはUp-Tの「ハッピ・ブルゾン > ハッピ・その他」配下の商品(A8リンクのURLより)。
// - Up-T公式サイトは取得できず、正式な商品名・販売状況・各商品の仕様は未照合。`verified: false` の間は、
//   画面に「取り扱い・仕様はUp-T公式で確認」と明記する。
// - 説明文はUp-T公式で確認できていない事実(納期・価格・対応可否・素材・サイズ)を含めない。
// - id は `?item=<id>` でLPへ直接リンクできる(リスティング・回遊LP・記事内リンクから利用)。既存idは変更しない
//   (ag_tshirt/mug/hoodie/polo/cap/apron/tote/towel/phonecase/keyholder が広告で使用中)。
// - `npm run` ではなく `node scripts/export-lp-items.cjs` で、id・LP URL・流入キーワード候補の一覧(CSV)を出力できる。

export type ProductGroupId = "wear" | "class" | "biz" | "bag" | "goods" | "special";

export interface ProductGroup {
  id: ProductGroupId;
  label: string;
}

